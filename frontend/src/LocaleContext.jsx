const LocaleContext = createContext(null);

export function LocaleProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      const savedLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY);
      return savedLanguage === "hi" || savedLanguage === "mr"
        ? savedLanguage
        : "en";
    } catch (error) {
      console.error("Unable to read saved language preference:", error);
      return "en";
    }
  });

  const setLanguage = useCallback((nextLanguage) => {
    if (!["en", "hi", "mr"].includes(nextLanguage)) {
      return;
    }

    setLanguageState(nextLanguage);

    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    } catch (error) {
      console.error("Unable to save language preference:", error);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = useCallback(
    (text) => translations[language]?.[text] || text,
    [language]
  );

  const value = useMemo(
    () => ({ language, setLanguage, t }),
    [language, setLanguage, t]
  );

  return (
    <LocaleContext.Provider value={value}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  const context = useContext(LocaleContext);

  if (!context) {
    throw new Error("useLocale must be used within LocaleProvider.");
  }

  return context;
}

export function LanguageSelector({ className = "" }) {
  const { language, setLanguage } = useLocale();

  return (
    <label className={`language-switcher ${className}`.trim()}>
      <span className="language-switcher-label">Language / भाषा</span>
      <select
        value={language}
        onChange={(event) => setLanguage(event.target.value)}
        aria-label="Select language / भाषा चुनें"
      >
        <option value="en">English</option>
        <option value="hi">हिन्दी</option>
        <option value="mr">मराठी</option>
      </select>
    </label>
  );
}
